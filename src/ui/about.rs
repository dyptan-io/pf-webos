//! The About & licenses screen: the build version, punktfunk's own licence, and the
//! generated third-party notices, as one scrollable wall of text.
//!
//! Every other punktfunk client shows the version here rather than in its navigation
//! chrome, which is why the sidebar no longer draws it (see `sidebar::draw_sidebar`).
//!
//! **Scrolling is hardware-accelerated, the same way the Settings modal's row list
//! is.** `THIRD-PARTY-NOTICES.txt` is ~10,000 source lines — wrapped to the card
//! width that's more like ~12,000 visual lines, far too tall to bake into one GPU
//! texture (see `App::scroll_geometry`/`ui::ContentWindow`'s docs on why About needs
//! a *windowed* content tile where Settings' 9 rows fit in one). [`wrap_document`]
//! wraps the whole document once, up front, into a flat list of visual lines with a
//! uniform per-line stride — the unit `ui::ScrollWindow`/`ui::ContentWindow` scroll
//! over — and [`draw_about_window`] rasterizes only a bounded slice of it at a time
//! (not through [`TextCache`], which would be a non-starter on this `SoC` for a
//! document this size — see `draw_text_uncached`'s docs). Scrolling within that
//! slice is then a pure `DrawCmd::TexCropped`, never a re-rasterize.
use crate::ui::render::Rect;
use crate::ui::text_raster::{FontId, TextRaster};
use anyhow::Result;

use super::*;

/// The packaged version (e.g. `0.4.0+git.abc12345`), threaded in at compile time via
/// `PKG_VERSION` by the Taskfile's build step. `Cargo.toml` deliberately stays a fixed
/// `0.0.1` (see CLAUDE.md), so a bare native `cargo build` falls back to
/// `CARGO_PKG_VERSION` rather than showing an empty marker.
pub const VERSION: &str = match option_env!("PKG_VERSION") {
    Some(v) => v,
    None => env!("CARGO_PKG_VERSION"),
};

/// punktfunk-webos' own licence, both halves of the `MIT OR Apache-2.0` dual grant.
const APP_LICENSE: &str = concat!(
    include_str!("../../LICENSE-MIT"),
    "\n\n=============================== Apache-2.0 ===============================\n\n",
    include_str!("../../LICENSE-APACHE"),
);

/// Third-party notices for every crate that links on the webOS target, plus the
/// bundled non-Rust components. Generated by `build.rs` during compilation — regenerate
/// (via `task notices`) whenever the dependency tree changes.
const THIRD_PARTY_NOTICES: &str = include_str!("../../THIRD-PARTY-NOTICES.txt");

/// The whole document, as one static line list. `include_str!` gives a `&'static str`,
/// so splitting it costs one `Vec` of string slices — no copying of the ~560 KB body.
pub fn about_lines() -> Vec<&'static str> {
    let mut out = vec![
        "punktfunk for webOS",
        "",
        "A native LG webOS TV client for punktfunk — low-latency desktop and",
        "game streaming. Built on the upstream punktfunk project; all credit for",
        "the protocol, FEC/crypto core, and host implementation belongs there.",
        "",
        "  https://github.com/dyptan-io/punktfunk-webos",
        "  https://git.unom.io/unom/punktfunk",
        "",
        "Licensed under MIT OR Apache-2.0, at your option.",
        "",
        "========================================================================",
        "PUNKTFUNK-WEBOS LICENCE",
        "========================================================================",
        "",
    ];
    out.extend(APP_LICENSE.lines());
    out.push("");
    out.extend(THIRD_PARTY_NOTICES.lines());
    out
}

pub const ABOUT_WIDTH_FRAC: f32 = 0.78;
/// Fraction of the panel height the card occupies — tall, since this is a reading page.
const ABOUT_HEIGHT_FRAC: f32 = 0.84;
const SIDE_PAD: i32 = 40;
/// Vertical gap between rendered lines, on top of the font's own height.
const LINE_GAP: i32 = 4;

pub fn about_card_rect(screen_w: u32, screen_h: u32) -> Rect {
    let height = (screen_h as f32 * ABOUT_HEIGHT_FRAC).round() as u32;
    modal_card_rect(screen_w, screen_h, ABOUT_WIDTH_FRAC, height)
}

/// The scrolling viewport inside `card`, below the header.
pub fn about_body_rect(card: Rect, fonts: &Fonts) -> Rect {
    let header_end = modal_header_end_y(fonts.raster, fonts.label, fonts.value, card, ABOUT_SUBTITLE_PROBE);
    let top = header_end + 20;
    let bottom = card.y() + card.height() as i32 - 28;
    Rect::new(
        card.x() + SIDE_PAD,
        top,
        card.width().saturating_sub(SIDE_PAD as u32 * 2),
        (bottom - top).max(0) as u32,
    )
}

/// A fixed-length stand-in for the real subtitle when measuring the header's height.
/// The subtitle is `Version <VERSION>` — one line at every realistic version string —
/// so the body rect stays put regardless of what the build stamped in.
const ABOUT_SUBTITLE_PROBE: &str = "Version 0.0.0+git.00000000";

/// Stride (px) between two consecutive wrapped visual lines at `font`'s size —
/// the uniform unit `ui::ScrollWindow`/`ui::ContentWindow` scroll over.
pub fn about_line_stride(raster: &dyn TextRaster, font: FontId) -> i32 {
    raster.height(font) + LINE_GAP
}

/// How many wrapped visual lines fit in `body` — used to clamp scrolling so the
/// page can't be scrolled past its own end.
pub fn about_visible_lines(body: Rect, raster: &dyn TextRaster, font: FontId) -> usize {
    (body.height() as i32 / about_line_stride(raster, font).max(1)).max(1) as usize
}

/// Wraps every source `line` to `width`, flattening into one list of visual
/// lines — a blank source line becomes one blank visual line (preserving its
/// paragraph gap), and a wrapped one expands to as many entries as it needs.
/// This is the one-time cost (text measurement, not rasterization) that gives
/// the whole document a uniform per-line stride, so it can scroll exactly like
/// Settings' fixed-height rows instead of needing per-source-line bookkeeping.
pub fn wrap_document(raster: &dyn TextRaster, font: FontId, lines: &[&str], width: u32) -> Vec<String> {
    let mut out = Vec::new();
    for line in lines {
        if line.trim().is_empty() {
            out.push(String::new());
        } else {
            // Wrapped, not clipped: this is licence text, and silently truncating it
            // would hide terms the screen exists to display.
            out.extend(wrap_text(raster, font, line, width));
        }
    }
    out
}

/// Draws wrapped visual lines `[start, start+len)` of `lines`, top-aligned at
/// this painter's own origin — the content tile's local space, which the GPU
/// compositor then crops/positions from (see `Tile::ScrollContent`'s docs).
/// Only called when `ui::ContentWindow` (re)bakes a window, not per frame.
pub fn draw_about_window(
    painter: &mut Painter,
    raster: &dyn TextRaster,
    font: FontId,
    lines: &[String],
    start: usize,
    len: usize,
) -> Result<()> {
    let step = about_line_stride(raster, font);
    for (i, line) in lines.iter().skip(start).take(len).enumerate() {
        if line.is_empty() {
            continue;
        }
        draw_text_uncached(painter, raster, font, line, 0, i as i32 * step, MUTED)?;
    }
    Ok(())
}
